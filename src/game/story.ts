/** 장면 이름으로 대사 목록을 꺼낸다 */
export function sceneLines(key: string, run: RunState): Line[] {
    const [kind, id, part] = key.split(':');
    if (kind === 'prologue') return PROLOGUE[run.cls];
    if (kind === 'region') return REGION[id] ?? [];
    if (kind === 'boss') return BOSS[id]?.[part as 'intro' | 'defeat'] ?? [];
    if (kind === 'epilogue') return EPILOGUE[run.cls];
    return [];
}

