export function heroBark(cls: ClassId, kind: keyof HeroBarks): string | null {
    const xs = HERO_BARKS[cls]?.[kind];
    return xs?.length ? xs[Math.floor(Math.random() * xs.length)] : null;
}

/** 정예는 이름 앞에 성향이 붙어 조금 더 거칠게 */
export function barkFor(lookKey: string, kind: keyof Barks): string | null {
    const b = BARKS[lookKey];
    if (!b) return null;
    const xs = b[kind];
    return xs[Math.floor(Math.random() * xs.length)] ?? null;
}

