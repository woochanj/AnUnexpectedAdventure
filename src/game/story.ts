/** 장면 이름으로 대사 목록을 꺼낸다 */
export function sceneLines(key: string, run: RunState): Line[] {
    const [kind, id, part] = key.split(':');
    if (kind === 'prologue') return PROLOGUE[run.cls];
    if (kind === 'region') {
        const view = REGION_VIEW[id];
        return view ? [view, ...(REGION_HERO[run.cls]?.[id] ?? []).map(H)] : [];
    }
    if (kind === 'boss') {
        const b = BOSS[id];
        if (!b) return [];
        const p = part as 'intro' | 'defeat';
        return [...b[p], ...(b.vs[run.cls]?.[p] ?? [])];
    }
    if (kind === 'epilogue') return EPILOGUE[run.cls];
    return [];
}

